namespace UniversalParser.Core.Formats.Riff;

/// <summary>
/// Readable names for common RIFF chunks. The raw 4CC remains the identifier in the title;
/// this table only supplies the leading human-readable part.
/// </summary>
internal static class RiffChunkNames
{
    private static readonly Dictionary<string, string> InfoTags = new(StringComparer.Ordinal)
    {
        ["IARL"] = "ArchivalLocation",
        ["IART"] = "Artist",
        ["ICMS"] = "Commissioned",
        ["ICMT"] = "Comment",
        ["ICNM"] = "Cinematographer",
        ["ICOP"] = "Copyright",
        ["ICRD"] = "CreationDate",
        ["ICRP"] = "Cropped",
        ["IDIM"] = "Dimensions",
        ["IDIT"] = "DigitizationTime",
        ["IDPI"] = "DotsPerInch",
        ["IENG"] = "Engineer",
        ["IGNR"] = "Genre",
        ["IKEY"] = "Keywords",
        ["ILGT"] = "Lightness",
        ["ILNG"] = "Language",
        ["IMED"] = "Medium",
        ["INAM"] = "Name",
        ["IMUS"] = "Music",
        ["IPLT"] = "PaletteEntryCount",
        ["IPRD"] = "Product",
        ["IPRO"] = "Producer",
        ["IPRT"] = "Part",
        ["ISBJ"] = "Subject",
        ["ISFT"] = "Software",
        ["ISHP"] = "Sharpness",
        ["ISMP"] = "SmpteTimeCode",
        ["ISRC"] = "Source",
        ["ISRF"] = "SourceForm",
        ["ITCH"] = "Technician",
        ["ITRK"] = "TrackNumber",
    };

    public static bool IsInfoTag(string id) => InfoTags.ContainsKey(id);

    /// <summary>True when the 4CC has a known name, even if no field handler exists for it.</summary>
    public static bool IsKnown(string id) => IsInfoTag(id) || Get(id, null) != "UnknownChunk";

    public static string Get(string id, string? parentType) => id switch
    {
        "RIFF" or "RF64" or "BW64" or "RIFX" => id,
        "LIST" => "List",
        "fmt " => "Format",
        "data" => "Data",
        "fact" => "Fact",
        "cue " => "CuePoints",
        "bext" => "BroadcastExtension",
        "ds64" => "Ds64",
        "JUNK" => "Junk",
        "PAD " => "Padding",
        "FILL" => "Fill",
        "avih" => "AviMainHeader",
        "strh" => "AviStreamHeader",
        "strf" => "AviStreamFormat",
        "idx1" => "AviIndex",
        "VP8X" => "ExtendedFileHeader",
        "VP8 " => "VP8Bitstream",
        "VP8L" => "VP8LBitstream",
        "ANIM" => "AnimationParameters",
        "ANMF" => "AnimationFrame",
        "ALPH" => "Alpha",
        "ICCP" => "ICCProfile",
        "EXIF" => "Exif",
        "XMP " => "Xmp",
        "anih" => "AniHeader",
        "icon" => "IconFrame",
        "colh" => "CollectionHeader",
        "vers" => "Version",
        "msyn" => "MasterSync",
        "insh" => "InstrumentHeader",
        "labl" => "Label",
        "ptbl" => "PoolTable",
        "lins" => "InstrumentList",
        "lrgn" => "RegionList",
        "rgn " => "Region",
        "rgn2" => "Region2",
        "wave" => "Wave",
        "rgnh" => "RegionHeader",
        "wsmp" => "WaveSample",
        "wlnk" => "WaveLink",
        "art1" => "Articulation",
        "cdl " => "ConnectionList",
        "ins " => "Instrument",
        "smpl" => "SampleLoop",
        "inst" => "Instrument",
        "wavl" => "WaveList",
        "slnt" => "Silence",
        "dmlh" => "ExtendedAviHeader",
        "indx" => "Index",
        _ when RiffOpenDmlParser.IsIndexId(id) => "StandardIndex",
        "vprp" => "VideoProperties",
        "strn" => "StreamName",
        "odml" => "OpenDmlHeader",
        "movi" => "MovieData",
        "hdrl" => "AviHeaderList",
        "adtl" => "AssociatedDataList",
        "fram" => "FrameList",
        "wvpl" => "WavePool",
        "CSET" => "CharacterSet",
        "id3 " => "Id3Tag",
        "hash" => "Hash",
        "BKHD" => "BankHeader",
        "DIDX" => "DataIndex",
        "DATA" => "DataSection",
        "HIRC" => "HircSection",
        "FMT " => "Format",
        "PROJ" => "Project",
        "BNKI" => "BankInfo",
        "FEV " => "FmodEventBank",
        "SND " => "Sound",
        _ when parentType == "INFO" && InfoTags.TryGetValue(id, out var infoName) => infoName,
        _ => "UnknownChunk",
    };
}
